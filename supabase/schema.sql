CREATE TABLE IF NOT EXISTS public.polytrack_profiles (
    token_hash text PRIMARY KEY,
    name text NOT NULL,
    car_colors text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.polytrack_scores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id text NOT NULL,
    user_hash text NOT NULL,
    name text NOT NULL,
    car_colors text NOT NULL,
    frames bigint NOT NULL CHECK (frames > 0),
    recording text NOT NULL CHECK (length(recording) <= 10000),
    verified_state boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (track_id, user_hash)
);

CREATE INDEX IF NOT EXISTS polytrack_scores_rank
    ON public.polytrack_scores (track_id, frames, id);

ALTER TABLE public.polytrack_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.polytrack_scores ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.submit_polytrack_score(
    p_track_id text,
    p_user_hash text,
    p_name text,
    p_car_colors text,
    p_frames bigint,
    p_recording text
) RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    result_id bigint;
BEGIN
    INSERT INTO public.polytrack_profiles (token_hash, name, car_colors, updated_at)
    VALUES (p_user_hash, p_name, p_car_colors, now())
    ON CONFLICT (token_hash) DO UPDATE
        SET name = EXCLUDED.name,
            car_colors = EXCLUDED.car_colors,
            updated_at = now();

    INSERT INTO public.polytrack_scores (track_id, user_hash, name, car_colors, frames, recording)
    VALUES (p_track_id, p_user_hash, p_name, p_car_colors, p_frames, p_recording)
    ON CONFLICT (track_id, user_hash) DO UPDATE
        SET name = EXCLUDED.name,
            car_colors = EXCLUDED.car_colors,
            frames = EXCLUDED.frames,
            recording = EXCLUDED.recording,
            created_at = now()
        WHERE EXCLUDED.frames < public.polytrack_scores.frames
    RETURNING id INTO result_id;

    IF result_id IS NULL THEN
        SELECT id INTO result_id
        FROM public.polytrack_scores
        WHERE track_id = p_track_id AND user_hash = p_user_hash;
    END IF;

    RETURN result_id;
END;
$$;

REVOKE ALL ON FUNCTION public.submit_polytrack_score(text, text, text, text, bigint, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.submit_polytrack_score(text, text, text, text, bigint, text) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.submit_polytrack_score(text, text, text, text, bigint, text) TO service_role;